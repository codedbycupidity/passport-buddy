#!/bin/bash

# Passport Buddy Development Manager
# Ensures consistent development environment setup

set -e  # Exit on error

# Colors
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

# Paths
PROJECT_ROOT="/Users/beck/github/mern&flutter"
BACKEND_DIR="$PROJECT_ROOT/backend"
FRONTEND_DIR="$PROJECT_ROOT/frontend"

# Functions
log_info() { echo -e "${BLUE}[INFO]${NC} $1"; }
log_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
log_warning() { echo -e "${YELLOW}[WARNING]${NC} $1"; }
log_error() { echo -e "${RED}[ERROR]${NC} $1"; }

check_prerequisites() {
    log_info "Checking prerequisites..."
    
    # Check Docker
    if ! command -v docker &> /dev/null; then
        log_error "Docker is not installed!"
        exit 1
    fi
    
    # Check Node
    if ! command -v node &> /dev/null; then
        log_error "Node.js is not installed!"
        exit 1
    fi
    
    # Check npm
    if ! command -v npm &> /dev/null; then
        log_error "npm is not installed!"
        exit 1
    fi
    
    log_success "All prerequisites installed"
}

check_mongodb() {
    log_info "Checking MongoDB container..."
    
    if docker ps | grep -q "mernflutter-mongo-1"; then
        log_success "MongoDB container is running"
        
        # Test connection
        if docker exec mernflutter-mongo-1 mongosh -u root -p pass --authenticationDatabase admin --eval "db.adminCommand('ping')" &> /dev/null; then
            log_success "MongoDB connection verified"
        else
            log_error "MongoDB authentication failed!"
            log_info "Restarting MongoDB container..."
            cd "$PROJECT_ROOT"
            docker-compose restart mongo
            sleep 5
        fi
    else
        log_warning "MongoDB container not running. Starting..."
        cd "$PROJECT_ROOT"
        docker-compose up -d mongo
        sleep 5
        
        # Verify it started
        if docker ps | grep -q "mernflutter-mongo-1"; then
            log_success "MongoDB container started"
        else
            log_error "Failed to start MongoDB container"
            exit 1
        fi
    fi
}

verify_env_files() {
    log_info "Verifying environment files..."
    
    # Backend .env
    if [ ! -f "$BACKEND_DIR/.env" ]; then
        log_warning "Creating backend .env file..."
        cat > "$BACKEND_DIR/.env" << 'EOF'
# Auto-generated by dev-manager.sh
NODE_ENV=development
PORT=3000
API_HOST=localhost

# MongoDB - Using Docker credentials
MONGO_URI=mongodb://root:pass@localhost:27017/passport_buddy?authSource=admin

# Security
JWT_SECRET=dev-secret-key-change-in-production
JWT_EXPIRES_IN=7d
JWT_COOKIE_EXPIRES_IN=7

# Email (using Resend)
EMAIL_PROVIDER=resend
RESEND_API_KEY=re_QqSxDnrK_FgNmb9qzdYxHLV8Y5yJJLawy
EMAIL_FROM=hello@xbullet.me
EMAIL_FROM_NAME=Passport Buddy

# Storage
STORAGE_TYPE=spaces
UPLOAD_DIR=./uploads
DO_SPACES_KEY=DO0026ZR2H3WW4F97N7K
DO_SPACES_SECRET=QrIZe6IGO3JgexBdpi3spPWNxIM61FExmySOcVKY9tA
DO_SPACES_ENDPOINT=nyc3.digitaloceanspaces.com
DO_SPACES_BUCKET=passportbuddy
DO_SPACES_REGION=nyc3

# Client URL
CLIENT_URL=http://localhost:3001,http://localhost:5173
